"use client";

import { useMemo, useState, type ReactNode } from "react";
import { BuildingIcon } from "@/components/icons";
import { Badge } from "@/components/ui/badge";
import { Notice } from "@/components/ui/notice";
import { Panel } from "@/components/ui/panel";
import { BRAND } from "@/config/brand";
import { formatNumber } from "@/lib/format";
import { PLANNED_DECISIONS } from "@/simulation/decisions";
import { DEMO_SCENARIOS, DEMO_SCENARIO_IDS, runDemoSimulation, type DemoScenarioId, type DemoSimulation } from "@/simulation/demo/scenarios";
import { PREVIEW_GAME_RULES } from "@/simulation/games";
import { periodLabel } from "@/simulation/periods";
import type { AppProps } from "../types";
import { DepartmentDirectory, DepartmentPerformance, rowsFromQuarter } from "./departments";
import { LiveCompany } from "./live-company";
import { Milestones } from "./milestones";
import { EarningsReportView } from "./earnings-report";
import { HistoryTable, KpiGrid, QuarterlyChart } from "./financials";

type View = "live" | "preview";

// The scenario lab is a developer tool. Production builds only show the default scenario.
const SCENARIO_LAB_ENABLED = process.env.NODE_ENV === "development";
const DEFAULT_SCENARIO: DemoScenarioId = "baseline";

export function CompanyApp({ openApp }: AppProps) {
  const [view, setView] = useState<View>("live");
  const [scenarioId, setScenarioId] = useState<DemoScenarioId>(DEFAULT_SCENARIO);
  const [seedVariant, setSeedVariant] = useState(1);
  const [reportIndex, setReportIndex] = useState<number | null>(null);

  const simulation = useMemo(() => runDemoSimulation(scenarioId, `CSH-DEMO-${seedVariant}`), [scenarioId, seedVariant]);
  const latestIndex = simulation.quarters.length - 1;
  const selectedReport = Math.min(reportIndex ?? latestIndex, latestIndex);

  return (
    <div className="space-y-4 p-4 @xl:p-6">
      <header className="flex flex-wrap items-end justify-between gap-3">
        <div className="flex items-center gap-3">
          <span aria-hidden="true" className="grid size-10 place-items-center rounded-xl bg-linear-to-br from-sky-500 to-blue-800 text-white ring-1 ring-white/20 ring-inset">
            <BuildingIcon className="size-5.5" />
          </span>
          <div>
            <h3 className="text-xl font-semibold tracking-tight">{BRAND.company}</h3>
            <p className="text-xs text-fg-muted">Company dashboard · Corporate Simulation v0.1</p>
          </div>
        </div>
        <div role="group" aria-label="Company data" className="flex rounded-lg bg-white/5 p-0.5 ring-1 ring-line ring-inset">
          {(
            [
              ["live", "Live company"],
              ["preview", "Simulation preview"],
            ] as const
          ).map(([key, label]) => (
            <button
              key={key}
              type="button"
              aria-pressed={view === key}
              onClick={() => setView(key)}
              className="rounded-md px-3 py-1 text-xs font-medium text-fg-muted aria-pressed:bg-surface-hover aria-pressed:text-fg aria-pressed:shadow-sm"
            >
              {label}
            </button>
          ))}
        </div>
      </header>

      {view === "live" ? (
        <LiveCompany onPlay={() => openApp("spreadsheet-wars")} />
      ) : (
        <Preview
          simulation={simulation}
          reportIndex={selectedReport}
          onSelectReport={setReportIndex}
          lab={
            SCENARIO_LAB_ENABLED ? (
              <ScenarioLab
                simulation={simulation}
                scenarioId={scenarioId}
                onScenario={(id) => {
                  setScenarioId(id);
                  setReportIndex(null);
                }}
                onReroll={() => setSeedVariant((v) => v + 1)}
                seedVariant={seedVariant}
              />
            ) : null
          }
        />
      )}
    </div>
  );
}

interface PreviewProps {
  simulation: DemoSimulation;
  reportIndex: number;
  onSelectReport: (index: number) => void;
  lab: ReactNode;
}

function Preview({ simulation, reportIndex, onSelectReport, lab }: PreviewProps) {
  const { quarters, reports, milestones, company } = simulation;
  const current = quarters.at(-1)!;
  const previous = quarters.at(-2);

  return (
    <div className="space-y-4">
      <Notice tone="warning" title="Simulation preview: fictional demo data">
        Every figure, employee and report on this tab is generated by the simulation from a fixed scenario (
        {company.scenario.label}). It is not live community data, nothing here is saved, and nothing is sent to the
        server. The shared company goes live once the server aggregates verified results.
      </Notice>

      {lab}

      <section aria-label="Company overview (demo)" className="space-y-2">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <h4 className="text-sm font-semibold">
            {periodLabel(current.periodId)} <span className="font-normal text-fg-muted">· quarter in progress</span>
          </h4>
          <Badge tone="warning">Demo data</Badge>
        </div>
        <KpiGrid current={current} previous={previous} />
      </section>

      <QuarterlyChart quarters={quarters} selectedIndex={reportIndex} onSelect={onSelectReport} />

      <EarningsReportView reports={reports} index={reportIndex} onSelect={onSelectReport} />

      <div className="grid gap-4 @4xl:grid-cols-[1fr_17rem]">
        <DepartmentPerformance rows={rowsFromQuarter(current)} />
        <div className="space-y-4">
          <Milestones milestones={milestones} />
          <Decisions />
        </div>
      </div>

      <section aria-label="Quarterly history table" className="space-y-2">
        <h4 className="text-sm font-semibold">Quarterly history</h4>
        <HistoryTable quarters={quarters} />
      </section>

      <DepartmentDirectory rules={PREVIEW_GAME_RULES} />
    </div>
  );
}

function Decisions() {
  return (
    <Panel title="Strategic decisions" description="Coming later. Not open for votes.">
      <ul className="space-y-2">
        {PLANNED_DECISIONS.map((d) => (
          <li key={d.id}>
            <p className="flex items-start justify-between gap-2 text-[13px]">
              {d.label} <Badge className="mt-0.5">Planned</Badge>
            </p>
            <p className="text-[11px] text-fg-subtle">{d.description}</p>
          </li>
        ))}
      </ul>
    </Panel>
  );
}

interface ScenarioLabProps {
  simulation: DemoSimulation;
  scenarioId: DemoScenarioId;
  seedVariant: number;
  onScenario: (id: DemoScenarioId) => void;
  onReroll: () => void;
}

/** Development builds only: explore scenarios. Not gameplay and not a vote. */
function ScenarioLab({ simulation, scenarioId, seedVariant, onScenario, onReroll }: ScenarioLabProps) {
  const scenario = DEMO_SCENARIOS[scenarioId];
  const rejected = simulation.contributions.flatMap((c) => c.rejected);
  const replays = rejected.filter((r) => r.reason === "seedReplay").length;
  const duplicates = rejected.filter((r) => r.reason === "duplicate").length;
  const raw = simulation.contributions.reduce((sum, c) => sum + c.totalRaw, 0);
  const credited = simulation.contributions.reduce((sum, c) => sum + c.totalCredited, 0);

  return (
    <section aria-labelledby="scenario-lab-title" className="rounded-xl border border-dashed border-warning/40 bg-warning/5 p-4">
      <div className="flex flex-wrap items-start justify-between gap-2">
        <div>
          <h4 id="scenario-lab-title" className="text-sm font-semibold">Developer scenario lab</h4>
          <p className="text-xs text-fg-muted">Development builds only. Changes the local preview; not gameplay and not a company vote.</p>
        </div>
        <Badge tone="warning">Dev only</Badge>
      </div>
      <div className="mt-3 flex flex-wrap items-center gap-2">
        <label htmlFor="scenario-select" className="text-xs text-fg-muted">
          Scenario
        </label>
        <select
          id="scenario-select"
          value={scenarioId}
          onChange={(e) => onScenario(e.target.value as DemoScenarioId)}
          className="rounded-md border border-line bg-surface-sunken px-2 py-1 text-xs text-fg"
        >
          {DEMO_SCENARIO_IDS.map((id) => (
            <option key={id} value={id}>
              {DEMO_SCENARIOS[id].label}
            </option>
          ))}
        </select>
        <button type="button" onClick={onReroll} className="rounded-md bg-white/6 px-2.5 py-1 text-xs font-medium ring-1 ring-line ring-inset hover:bg-white/10">
          Reroll seed
        </button>
        <span className="font-mono text-[11px] text-fg-subtle">CSH-DEMO-{seedVariant}</span>
      </div>
      <p className="mt-2 text-xs text-fg-muted">{scenario.description}</p>
      <dl className="mt-2 grid grid-cols-2 gap-x-4 gap-y-0.5 text-[11px] @xl:grid-cols-4">
        {[
          ["Rounds generated", formatNumber(simulation.company.events.length)],
          ["Seed replays rejected", formatNumber(replays)],
          ["Duplicates rejected", formatNumber(duplicates)],
          ["Points removed by player caps", formatNumber(raw - credited)],
        ].map(([label, value]) => (
          <div key={label} className="flex justify-between gap-2 @xl:block">
            <dt className="text-fg-subtle">{label}</dt>
            <dd className="tabular-nums">{value}</dd>
          </div>
        ))}
      </dl>
    </section>
  );
}
